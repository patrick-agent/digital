export function getAllPosts() {
  return blogPosts.sort((a, b) => new Date(b.date) - new Date(a.date));
}

export function getPostBySlug(slug) {
  return blogPosts.find((p) => p.slug === slug) || null;
}

export function getAllTags() {
  const tags = new Set();
  blogPosts.forEach((post) => {
    (post.tags || []).forEach((tag) => tags.add(tag));
  });
  return ['All', ...Array.from(tags).sort()];
}

export function getTagCounts() {
  const counts = { All: blogPosts.length };
  blogPosts.forEach((post) => {
    (post.tags || []).forEach((tag) => {
      counts[tag] = (counts[tag] || 0) + 1;
    });
  });
  return counts;
}

export function getRelatedPosts(currentSlug, tags, limit = 3) {
  const others = blogPosts.filter((p) => p.slug !== currentSlug);
  const scored = others.map((post) => {
    const overlap = (post.tags || []).filter((t) => (tags || []).includes(t)).length;
    return { ...post, score: overlap };
  });
  scored.sort((a, b) => b.score - a.score || new Date(b.date) - new Date(a.date));
  return scored.slice(0, limit);
}
